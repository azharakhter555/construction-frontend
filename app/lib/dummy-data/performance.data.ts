// ─────────────────────────────────────────────────────────────
// KPIs — computed from rows so they always match the table
// ─────────────────────────────────────────────────────────────

export function computeKpis(rows: InstructorPerformance[]): PerformanceKpis {
  if (rows.length === 0) {
    return {
      totalInstructors: 0,
      totalReviews: 0,
      averageRating: 0,
      averagePassRate: 0,
      topPerformer: null,
      newReviewsThisMonth: 0,
    };
  }

  const totalReviews = rows.reduce((n, r) => n + r.totalReviews, 0);
  const averageRating = rows.reduce((n, r) => n + r.averageRating, 0) / rows.length;
  const averagePassRate = rows.reduce((n, r) => n + r.passRate, 0) / rows.length;

  const top = [...rows].sort((a, b) => b.averageRating - a.averageRating)[0];

  // "New reviews this month" — count rows whose lastReviewAt is in the current month
  const now = new Date();
  const newReviewsThisMonth = rows.filter((r) => {
    if (!r.lastReviewAt) return false;
    const d = new Date(r.lastReviewAt);
    return d.getUTCFullYear() === now.getUTCFullYear() && d.getUTCMonth() === now.getUTCMonth();
  }).length;

  return {
    totalInstructors: rows.length,
    totalReviews,
    averageRating: Number(averageRating.toFixed(2)),
    averagePassRate: Number(averagePassRate.toFixed(1)),
    topPerformer: top
      ? {
          name: `${top.user.firstName} ${top.user.lastName}`,
          rating: top.averageRating,
        }
      : null,
    newReviewsThisMonth,
  };
}

