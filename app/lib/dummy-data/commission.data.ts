// ── KPIs derived from rows ──

export function computeCommissionKpis(rows: CommissionRow[]): CommissionKpis {
  if (rows.length === 0) {
    return {
      totalInstructors: 0,
      overriddenCount: 0,
      defaultRate: DEFAULT_PLATFORM_RATE,
      monthlyCommission: 0,
      totalCommission: 0,
      topEarner: null,
      averageRate: 0,
    };
  }

  const overriddenCount = rows.filter(
    (r) => r.overrideRate !== null || r.overrideType === "fixed"
  ).length;
  const monthlyCommission = rows.reduce((n, r) => n + r.monthlyCommission, 0);
  const totalCommission = rows.reduce((n, r) => n + r.totalCommission, 0);
  const averageRate = rows.reduce((n, r) => n + r.effectiveRate, 0) / rows.length;

  const top = [...rows].sort((a, b) => b.monthlyCommission - a.monthlyCommission)[0];

  return {
    totalInstructors: rows.length,
    overriddenCount,
    defaultRate: DEFAULT_PLATFORM_RATE,
    monthlyCommission: Number(monthlyCommission.toFixed(2)),
    totalCommission: Number(totalCommission.toFixed(2)),
    topEarner: top
      ? {
          name: `${top.user.firstName} ${top.user.lastName}`,
          amount: top.monthlyCommission,
        }
      : null,
    averageRate: Number(averageRate.toFixed(2)),
  };
}

export const dummyCommissionKpis = computeCommissionKpis(dummyCommissionRows);
